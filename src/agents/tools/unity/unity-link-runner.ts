/**
 * Unity Link — the ONE interactive step of the asset-store story.
 *
 * The headless my-assets-cloud flow needs a packman refresh token. Getting the
 * first one requires the user's interactive Unity sign-in consent — which only
 * the Editor can show properly. This runner generates a self-contained C#
 * consent script into a minimal scratch project and launches the editor
 * (batch mode, NOT -nographics so the sign-in dialog can appear). The script:
 *
 *   1. Reads UnityConnect's configuration (identity host, packages host,
 *      packman client key) via reflection — the same internal call the
 *      Enhanced Package Manager proved out.
 *   2. Calls UnityOAuth.GetAuthorizationCodeAsync("packman", cb) → the user's
 *      standard Unity sign-in dialog appears once.
 *   3. Exchanges the code at POST {identity}/v1/oauth2/token.
 *   4. Writes {refreshToken, identityHost, packagesHost, clientSecret, linkedAt}
 *      to a JSON file this runner then moves to ~/.strada/unity-asset-store.json
 *      (chmod 600) — after that, everything is headless refresh.
 */

import { mkdirSync, writeFileSync, readFileSync, existsSync, rmSync, chmodSync, readdirSync } from "node:fs";
import { execFile } from "node:child_process";
import { join, dirname } from "node:path";
import { homedir } from "node:os";
import { z } from "zod";
import { getLoggerSafe } from "../../../utils/logger.js";

// =============================================================================
// CONSENT SCRIPT (self-contained C#, mirrors the proven reflection recipe)
// =============================================================================

export const CONSENT_SCRIPT = `// Generated by Strada.Brain Unity Link — one-time packman OAuth consent (code step only).
// The code EXCHANGE is done outside the editor: the editor's UnityConnect config
// (CloudPackagesApi/CloudPackagesKey) is only populated for Hub-launched editors
// (measured 2026-08-27 on 6000.3.22f1), so the runner reads the same values from
// the Hub's own cloudConfig.json and does the HTTPS exchange itself.
using System;
using System.IO;
using System.Reflection;
using System.Text;
using System.Threading.Tasks;
using UnityEditor;
using UnityEngine;

public static class StradaLinkConsent
{
    const string ClientId = "packman";

    static bool _done;
    static int _exitCode = 1;
    static string _outPath;

    public static void Run()
    {
        Debug.Log("UNITY-LINK-START");
        var args = Environment.GetCommandLineArgs();
        for (int i = 0; i < args.Length - 1; i++)
            if (args[i] == "-linkOutput") _outPath = args[i + 1];
        if (string.IsNullOrEmpty(_outPath))
        {
            Debug.LogError("UNITY-LINK-FAIL: no -linkOutput path");
            EditorApplication.Exit(1);
            return;
        }
        EditorApplication.update += Pump;
        Flow();
    }

    static void Pump()
    {
        if (!_done) return;
        EditorApplication.update -= Pump;
        EditorApplication.Exit(_exitCode);
    }

    static async void Flow()
    {
        try
        {
            var code = await GetAuthorizationCode();
            File.WriteAllText(_outPath, "{\\"code\\":\\"" + code + "\\"}");
            Debug.Log("UNITY-LINK-OK");
            _exitCode = 0;
        }
        catch (Exception e)
        {
            Debug.LogError("UNITY-LINK-FAIL: " + e.Message);
            _exitCode = 1;
        }
        finally
        {
            _done = true;
        }
    }

    static Task<string> GetAuthorizationCode()
    {
        var tcs = new TaskCompletionSource<string>();
        try
        {
            var editorAssembly = typeof(UnityEditor.Editor).Assembly;
            var oauthType = editorAssembly.GetType("UnityEditor.Connect.UnityOAuth");
            if (oauthType == null)
                foreach (var asm in AppDomain.CurrentDomain.GetAssemblies())
                {
                    if (asm.IsDynamic) continue;
                    oauthType = asm.GetType("UnityEditor.Connect.UnityOAuth");
                    if (oauthType != null) break;
                }
            if (oauthType == null) throw new Exception("UnityOAuth type not found");

            MethodInfo target = null;
            foreach (var m in oauthType.GetMethods(BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic))
            {
                if (m.Name != "GetAuthorizationCodeAsync") continue;
                var ps = m.GetParameters();
                if (ps.Length == 2 && ps[0].ParameterType == typeof(string)) { target = m; break; }
            }
            if (target == null) throw new Exception("GetAuthorizationCodeAsync(string, Action<>) not found");

            var responseType = target.GetParameters()[1].ParameterType.GetGenericArguments()[0];
            Action<object> handler = (resp) =>
            {
                // The callback delivers the code AS A STRING (measured live:
                // resp was System.String, 26 chars — not an object with a
                // .code property). Check that first; object shapes fall back
                // to property reading below.
                if (resp is string codeString && !string.IsNullOrEmpty(codeString))
                {
                    tcs.TrySetResult(codeString);
                    return;
                }
                // Read against the RUNTIME type: the declared Action<T> generic
                // arg and the delivered object can differ (TargetException,
                // measured 2026-08-27), and reading properties of the declared
                // type against the runtime object is what blew up the first pass.
                var actualType = resp.GetType();
                string code = null;
                foreach (var name in new[] { "code", "Code", "authCode", "AuthCode", "authorizationCode", "AuthorizationCode" })
                {
                    try
                    {
                        var prop = actualType.GetProperty(name, BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic);
                        if (prop != null) { code = prop.GetValue(resp, null) as string; if (!string.IsNullOrEmpty(code)) break; }
                        var field = actualType.GetField(name, BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic);
                        if (field != null) { code = field.GetValue(resp) as string; if (!string.IsNullOrEmpty(code)) break; }
                    }
                    catch { /* try the next name */ }
                }
                if (!string.IsNullOrEmpty(code))
                {
                    tcs.TrySetResult(code);
                    return;
                }
                // Diagnostic: the actual shape of the response, so a failure
                // names the real property instead of "empty".
                var sb = new StringBuilder();
                sb.Append("type=").Append(actualType.FullName).Append("; ");
                foreach (var p in actualType.GetProperties(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic))
                {
                    object v = null;
                    try { v = p.GetValue(resp, null); } catch { }
                    sb.Append(p.Name).Append("=").Append(v == null ? "null" : (v is string s && s.Length > 40 ? s.Substring(0, 40) + "…" : v.ToString())).Append("; ");
                }
                foreach (var f in actualType.GetFields(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic))
                {
                    object v = null;
                    try { v = f.GetValue(resp); } catch { }
                    sb.Append(f.Name).Append("=").Append(v == null ? "null" : (v is string s2 && s2.Length > 40 ? s2.Substring(0, 40) + "…" : v.ToString())).Append("; ");
                }
                tcs.TrySetException(new Exception("empty authorization code. Response shape: " + sb));
            };
            var del = Delegate.CreateDelegate(target.GetParameters()[1].ParameterType, handler.Target, handler.Method);
            try
            {
                target.Invoke(null, new object[] { ClientId, del });
            }
            catch (Exception invokeError)
            {
                // MethodInfo.Invoke wraps the real error — surface the inner one.
                var inner = invokeError.InnerException != null ? invokeError.InnerException : invokeError;
                throw new Exception("GetAuthorizationCodeAsync failed: " + inner.GetType().Name + ": " + inner.Message);
            }
        }
        catch (Exception e)
        {
            tcs.TrySetException(e);
        }
        return tcs.Task;
    }
}
`;

