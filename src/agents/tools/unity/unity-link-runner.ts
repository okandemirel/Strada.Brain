const linkSchema = z.object({
  refreshToken: z.string().min(10),
  identityHost: z.string().url().startsWith("https://"),
  packagesHost: z.string().url().startsWith("https://"),
  clientSecret: z.string().min(1),
  linkedAt: z.number(),
});

export interface UnityLinkResult {
  ok: boolean;
  detail: string;
  linkFile?: string;
}

export interface UnityLinkRunnerOptions {
  unityBin?: string;
  timeoutMs?: number;
  /** Test seam: replace the Unity process spawn. */
  spawnImpl?: typeof execFile;
}

const DEFAULT_UNITY_BIN = "/Applications/Unity/Hub/Editor/6000.3.22f1/Unity.app/Contents/MacOS/Unity";
const LINK_STORE = join(homedir(), ".strada", "unity-asset-store.json");

/** Read ProjectVersion from a real project if present, else the default. */
function editorVersion(): string {
  try {
    const v = readFileSync(
      "/Users/okan/Documents/MaxedOutEntertainment/PixelFlow-Clean/ProjectSettings/ProjectVersion.txt",
      "utf8",
    );
    const m = /m_EditorVersion:\s*(\S+)/.exec(v);
    if (m) return m[1]!;
  } catch {
    /* fall through */
  }
  return "6000.3.22f1";
}

export async function runUnityLink(options: UnityLinkRunnerOptions = {}): Promise<UnityLinkResult> {
  const unityBin = options.unityBin ?? resolveUnityBin();
  if (!existsSync(unityBin)) {
    return { ok: false, detail: `Unity editor not found at ${unityBin}` };
  }

  const scratch = mkdtempSync(join(tmpdir(), "strada-unity-link-"));
  const outputPath = join(scratch, "link-result.json");
  const logPath = join(scratch, "editor.log");
  const timeoutMs = options.timeoutMs ?? 5 * 60_000;

  try {
    mkdirSync(join(scratch, "Assets", "Editor"), { recursive: true });
    mkdirSync(join(scratch, "ProjectSettings"), { recursive: true });
    writeFileSync(join(scratch, "Assets", "Editor", "StradaLinkConsent.cs"), CONSENT_SCRIPT, "utf8");
    writeFileSync(
      join(scratch, "ProjectSettings", "ProjectVersion.txt"),
      `m_EditorVersion: ${editorVersion()}\n`,
      "utf8",
    );

    const spawn = options.spawnImpl ?? execFile;
    const exitCode = await new Promise<number>((resolvePromise) => {
      const child = spawn(
        unityBin,
        [
          "-batchmode",
          "-projectPath", scratch,
          "-executeMethod", "StradaLinkConsent.Run",
          "-logFile", logPath,
          "-linkOutput", outputPath,
        ],
        { timeout: timeoutMs },
        (error) => {
          if (error) {
            resolvePromise(typeof error.code === "number" ? error.code : 1);
          } else {
            resolvePromise(0);
          }
        },
      );
      child.unref?.();
    });

    if (exitCode !== 0 || !existsSync(outputPath)) {
      const logTail = existsSync(logPath)
        ? readFileSync(logPath, "utf8").split("\n").filter((l) => l.includes("UNITY-LINK")).slice(-3).join(" | ")
        : "no editor log";
      return { ok: false, detail: `Unity link failed (exit ${exitCode}): ${logTail}` };
    }

    const parsed = linkSchema.safeParse(JSON.parse(readFileSync(outputPath, "utf8")));
    if (!parsed.success) {
      return { ok: false, detail: `Unity link wrote an invalid token file: ${z.prettifyError(parsed.error).slice(0, 200)}` };
    }

    mkdirSync(join(homedir(), ".strada"), { recursive: true });
    writeFileSync(LINK_STORE, JSON.stringify(parsed.data, null, 2), { mode: 0o600 });
    chmodSync(LINK_STORE, 0o600);
    getLoggerSafe().info("Unity account linked for Asset Store access", { linkFile: LINK_STORE });
    return { ok: true, detail: `Unity account linked. Token store: ${LINK_STORE}`, linkFile: LINK_STORE };
  } catch (err) {
    return { ok: false, detail: `Unity link failed: ${err instanceof Error ? err.message : String(err)}` };
  } finally {
    try {
      rmSync(scratch, { recursive: true, force: true });
    } catch {
      /* scratch cleanup is best-effort */
    }
  }
}

function resolveUnityBin(): string {
  const editorsDir = "/Applications/Unity/Hub/Editor";
  try {
    const versions = readdirSync(editorsDir, { withFileTypes: true })
      .filter((e) => e.isDirectory())
      .map((e) => e.name)
      .sort()
      .reverse();
    if (versions.length > 0) {
      return join(editorsDir, versions[0]!, "Unity.app", "Contents", "MacOS", "Unity");
    }
  } catch {
    /* fall back to the default path */
  }
  return DEFAULT_UNITY_BIN;
}
